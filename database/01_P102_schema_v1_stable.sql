-- 統計 Views
CREATE OR REPLACE VIEW public."ViewP102PopularKeywords" AS
SELECT "Keyword", COUNT(*) AS "SearchCount", AVG("ResultCount") AS "AverageResultCount", MAX("CreatedAt") AS "LastSearchedAt"
FROM public."TblP102SearchEvents"
GROUP BY "Keyword"
ORDER BY "SearchCount" DESC;

CREATE OR REPLACE VIEW public."ViewP102SearchFailures" AS
SELECT "Keyword", COUNT(*) AS "FailureCount", MAX("CreatedAt") AS "LastFailedAt"
FROM public."TblP102SearchFailures"
GROUP BY "Keyword"
ORDER BY "FailureCount" DESC;

CREATE OR REPLACE VIEW public."ViewP102PopularSpaces" AS
SELECT "SpaceNo", "SpaceName", COUNT(*) AS "ViewCount", MAX("CreatedAt") AS "LastViewedAt"
FROM public."TblP102SpaceViewEvents"
GROUP BY "SpaceNo", "SpaceName"
ORDER BY "ViewCount" DESC;
