CREATE INDEX IF NOT EXISTS "idx_TblP102SearchEvents_Keyword" ON public."TblP102SearchEvents" ("Keyword");
CREATE INDEX IF NOT EXISTS "idx_TblP102SearchFailures_Keyword" ON public."TblP102SearchFailures" ("Keyword");
CREATE INDEX IF NOT EXISTS "idx_TblP102SpaceViewEvents_SpaceNo" ON public."TblP102SpaceViewEvents" ("SpaceNo");
CREATE INDEX IF NOT EXISTS "idx_TblP102Feedback_SpaceNo" ON public."TblP102Feedback" ("SpaceNo");

