  "AliasID" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "SpaceNo" text NOT NULL,
  "AliasName" text NOT NULL,
  "LanguageCode" text NOT NULL DEFAULT 'zh-TW',
  "AliasType" text DEFAULT 'nickname',
  "IsActive" boolean DEFAULT true,
  "SortOrder" integer DEFAULT 0,
  "CreatedAt" timestamptz DEFAULT now(),
  "UpdatedAt" timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "idx_TblP102SpaceAlias_SpaceNo" ON public."TblP102SpaceAlias" ("SpaceNo");
CREATE INDEX IF NOT EXISTS "idx_TblP102SpaceAlias_AliasName" ON public."TblP102SpaceAlias" ("AliasName");

-- 查詢紀錄
CREATE TABLE IF NOT EXISTS public."TblP102SearchEvents" (
