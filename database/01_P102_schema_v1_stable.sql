-- 主表欄位補強
ALTER TABLE public."TblP102Space" ADD COLUMN IF NOT EXISTS "FloorMapPic" text;
ALTER TABLE public."TblP102Space" ADD COLUMN IF NOT EXISTS "CampusMapPic" text;

UPDATE public."TblP102Space"
SET "FloorMapPic" = COALESCE("FloorMapPic", "PicNo")
WHERE "FloorMapPic" IS NULL AND "PicNo" IS NOT NULL;

UPDATE public."TblP102Space"
SET "CampusMapPic" = COALESCE("CampusMapPic", "PicNo")
WHERE "CampusMapPic" IS NULL AND "PicNo" IS NOT NULL;

-- 修正第三校區校區圖規則：3A1/3B1/... -> 3ABCDEF1；3AB1 -> 3ABCDEFB1
UPDATE public."TblP102Space"
SET "CampusMapPic" = REGEXP_REPLACE("PicNo", '^3AB', '3ABCDEFB')
WHERE "PicNo" ~ '^3AB';

UPDATE public."TblP102Space"
SET "CampusMapPic" = REGEXP_REPLACE("PicNo", '^3[A-F]', '3ABCDEF')
WHERE "PicNo" ~ '^3[A-F]' AND "PicNo" !~ '^3AB';

-- 修正曾經重複替換造成的錯誤
UPDATE public."TblP102Space"
SET "CampusMapPic" = REGEXP_REPLACE("CampusMapPic", '^3ABCDEFBCDEF', '3ABCDEF')
WHERE "CampusMapPic" LIKE '3ABCDEFBCDEF%';

COMMENT ON COLUMN public."TblP102Space"."FloorMapPic" IS '樓層平面圖檔名，不含副檔名。前端讀取 jpg/{FloorMapPic}.jpg。';
COMMENT ON COLUMN public."TblP102Space"."CampusMapPic" IS '校區總覽圖檔名，不含副檔名。前端讀取 jpg/{CampusMapPic}.jpg。';

-- 多語言別名表
