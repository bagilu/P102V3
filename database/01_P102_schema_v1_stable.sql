-- RPCs: 前端透過 SECURITY DEFINER 寫入紀錄，不直接開放 anon insert policy。
CREATE OR REPLACE FUNCTION public."P102AddSearchEvent"(p_keyword text, p_result_count integer, p_matched_by text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  INSERT INTO public."TblP102SearchEvents" ("Keyword", "ResultCount", "MatchedBy")
  VALUES (p_keyword, p_result_count, p_matched_by);
END;
$$;
GRANT EXECUTE ON FUNCTION public."P102AddSearchEvent"(text, integer, text) TO anon;

CREATE OR REPLACE FUNCTION public."P102AddSearchFailure"(p_keyword text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  INSERT INTO public."TblP102SearchFailures" ("Keyword") VALUES (p_keyword);
END;
$$;
GRANT EXECUTE ON FUNCTION public."P102AddSearchFailure"(text) TO anon;

CREATE OR REPLACE FUNCTION public."P102AddSpaceViewEvent"(p_space_no text, p_space_name text, p_campus_no text, p_floor_map_pic text, p_campus_map_pic text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
