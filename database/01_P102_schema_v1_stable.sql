  VALUES (p_space_no, p_space_name, p_campus_no, p_floor_map_pic, p_campus_map_pic);
END;
$$;
GRANT EXECUTE ON FUNCTION public."P102AddSpaceViewEvent"(text, text, text, text, text) TO anon;

CREATE OR REPLACE FUNCTION public."P102AddFeedback"(p_space_no text, p_space_name text, p_feedback_type text, p_feedback_text text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
